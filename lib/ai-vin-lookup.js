import { callGeminiSearchJson } from './gemini.js';

// Фолбэк, когда Laximo НЕ распознал VIN (findVehicle вернул пустой массив) — Laximo не покрывает
// все рынки/года (см. память проекта: слабо покрывает свежие US Copart VIN и не покрывает Lada вообще).
// Вместо немедленного "не найдено" просим Gemini (с веб-поиском) самому определить автомобиль по VIN
// и найти OEM-номера нужных деталей — тем же способом, каким это делал бы человек через VIN-декодер + гуглёж.
//
// ИСПРАВЛЕНО 26.09.2026: раньше этот вызов искал ТОЛЬКО оригинальный OEM, а если сверка с таблицей
// наличия (lib/ai-match.js) не находила прямого совпадения, код делал ВТОРОЙ отдельный вызов Gemini
// с веб-поиском кросс-номеров/аналогов — то есть при "холодном" запросе реальный ответ клиенту ждал
// ДВА последовательных обращения в интернет подряд (суммарно легко уходило за 30-50с, упираясь
// в лимит Vercel и в таймаут вебхук-экшена Savvy — часть запросов не доходила до клиента вообще).
// Теперь оба типа номеров запрашиваются В ОДНОМ запросе — второго сетевого вызова для кросс-номеров
// больше нет, lib/ai-match.js сверяет уже готовый список чистым кодом без обращения в Gemini.
//
// parts: [{ key, description }] — key используется как ключ в возвращаемом объекте parts,
// description — человекочитаемое описание нужной детали для промпта (на русском).
// deadline (опционально) — Date.now()-метка, до которой должен уложиться этот вызов Gemini;
// используется вызывающим кодом (api/*.js) для сквозного тайм-бюджета на весь запрос,
// см. комментарий в lib/gemini.js. Без deadline — дефолт 30с (для обратной совместимости).
// Возвращает { found, carName, parts: { [key]: { oem, partName, crossReferences } } } или null
// (нет ключа/сети/не удалось распарсить/авто не определено).
export async function findVehiclePartsViaAI(vin, parts, { deadline } = {}) {
  const partsList = parts.map(p => `- "${p.key}": ${p.description}`).join('\n');

  const prompt = `По VIN-номеру автомобиля "${vin}" определи марку, модель, поколение и год выпуска
(используй свои знания и поиск в интернете — VIN-декодеры, каталоги запчастей, форумы).

Затем для каждой из следующих деталей:
1) найди оригинальный OEM-номер (номер запчасти производителя), который подходит именно для этого
   автомобиля (с учётом платформы/поколения/комплектации, если это важно);
2) В ТОМ ЖЕ поиске сразу найди и известные альтернативные номера для этой же детали:
   - неоригинальные/кросс-номера — взаимозаменяемые аналоги от известных производителей автозапчастей
     (Febi, Blue Print, VAICO, TYC, Depo и т.п.);
   - официальные оригинальные номера-замены той же детали от того же производителя (например, при
     рестайлинге модели или изменении в производстве завод мог перевыпустить физически ту же/очень
     похожую деталь под новым номером — supersession/replacement part number, старый и новый OEM).
${partsList}

Если марка автомобиля — Ford, Land Rover (включая Range Rover, Jaguar Land Rover) или Porsche: ищи именно
заводской инженерный номер детали (Engineering Part Number / конструкторский номер — тот, что указан
в технической/конструкторской документации производителя и часто отлит или выштампован на самой
детали), а НЕ сервисный/дилерский каталожный номер (Service Part Number) для заказа через
официальную дилерскую сеть — у этих марок они часто отличаются, нужен именно инженерный номер.

Ответь СТРОГО в формате JSON, без пояснений и без markdown-разметки:
{"found": true, "car_name": "<марка модель год>", "parts": {"<key>": {"oem": "<номер>", "part_name": "<название детали>", "cross_references": ["<номер1>", "<номер2>", ...]}, ...}}

Если для какой-то детали не удалось уверенно найти OEM — не включай её ключ в "parts" (пропусти, не выдумывай номер).
Если альтернативных номеров для детали не нашлось — верни "cross_references": [] (пустой список, не выдумывай номера).
Если сам автомобиль по VIN определить не удалось вообще — ответь: {"found": false}`;

  // ИСПРАВЛЕНО 19.09.2026: раньше VIN-lookup брал ВЕСЬ оставшийся бюджет запроса без остатка
  // (Math.max(0, deadline - Date.now())) — на практике это означало, что шагам ПОСЛЕ него
  // (сверка наличия уровня 2 — кросс-референс по таблице через ещё один вызов Gemini) почти
  // никогда не доставалось времени и они гарантированно обрывались по таймауту (видно в живых
  // Vercel-логах — 19.09.2026, "Gemini request threw (or timed out): AbortError" на КАЖДОМ
  // запросе, и availability.found:false во всех живых тестах в тот же день). Раньше (06.09)
  // у VIN-lookup и уровня 2 были отдельные фиксированные бюджеты 30с/15с — этот кап их
  // фактически восстанавливает, просто внутри общей модели "один дедлайн на весь запрос".
  // Поднят с 30000 (26.09.2026): раньше за VIN-lookup всегда следовал ВТОРОЙ вызов Gemini
  // (кросс-номера, lib/ai-match.js) с собственным бюджетом — общий кап 30с держал запас для него.
  // Теперь кросс-номера ищутся в этом же вызове и второго обращения в Gemini не будет вообще,
  // так что этому единственному вызову можно отдать больше времени из общего дедлайна запроса.
  const MAX_VIN_LOOKUP_MS = 40000;
  const timeoutMs = deadline ? Math.min(MAX_VIN_LOOKUP_MS, Math.max(0, deadline - Date.now())) : 30000;
  const parsed = await callGeminiSearchJson(prompt, { timeoutMs });
  if (!parsed?.found || !parsed.car_name) return null;

  return {
    found: true,
    carName: parsed.car_name,
    parts: parsed.parts && typeof parsed.parts === 'object' ? parsed.parts : {}
  };
}
